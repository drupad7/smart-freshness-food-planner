import os
import sqlite3
from contextlib import closing
from pathlib import Path
from dotenv import load_dotenv

import psycopg
from psycopg.rows import dict_row

load_dotenv()
BASE_DIR = Path(__file__).resolve().parent
DB_PATH = BASE_DIR / "data" / "sensor_readings.db"


def _get_database_url(db_path=None):
    """Use PostgreSQL only when no explicit SQLite path is provided."""
    if db_path is not None:
        return None

    return os.getenv("DATABASE_URL")


def init_db(db_path=None):
    """Initialize the local SQLite or cloud PostgreSQL database."""
    database_url = _get_database_url(db_path)

    if database_url:
        with psycopg.connect(database_url) as connection:
            connection.execute("""
                CREATE TABLE IF NOT EXISTS public.sensor_readings (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    device_id TEXT NOT NULL,
                    "timestamp" TIMESTAMPTZ NOT NULL,
                    temperature DOUBLE PRECISION NOT NULL,
                    humidity DOUBLE PRECISION NOT NULL,
                    gas_raw INTEGER NOT NULL,
                    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
                )
            """)

            connection.execute("""
                CREATE INDEX IF NOT EXISTS idx_sensor_readings_timestamp
                ON public.sensor_readings ("timestamp" DESC)
            """)
        return

    path = Path(db_path) if db_path is not None else DB_PATH
    path.parent.mkdir(parents=True, exist_ok=True)

    with closing(sqlite3.connect(path)) as connection:
        with connection:
            connection.execute("""
                CREATE TABLE IF NOT EXISTS sensor_readings (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    device_id TEXT NOT NULL,
                    timestamp TEXT NOT NULL,
                    temperature REAL NOT NULL,
                    humidity REAL NOT NULL,
                    gas_raw INTEGER NOT NULL
                )
            """)


def save_reading(reading, db_path=None):
    """Save a sensor reading and return its database ID."""
    database_url = _get_database_url(db_path)

    if database_url:
        init_db()

        with psycopg.connect(database_url) as connection:
            row = connection.execute("""
                INSERT INTO public.sensor_readings (
                    device_id,
                    "timestamp",
                    temperature,
                    humidity,
                    gas_raw
                )
                VALUES (%s, %s, %s, %s, %s)
                RETURNING id
            """, (
                reading["device_id"],
                reading["timestamp"],
                reading["temperature"],
                reading["humidity"],
                reading["gas_raw"],
            )).fetchone()

            return row[0]

    path = Path(db_path) if db_path is not None else DB_PATH
    init_db(path)

    with closing(sqlite3.connect(path)) as connection:
        with connection:
            cursor = connection.execute("""
                INSERT INTO sensor_readings (
                    device_id,
                    timestamp,
                    temperature,
                    humidity,
                    gas_raw
                )
                VALUES (?, ?, ?, ?, ?)
            """, (
                reading["device_id"],
                reading["timestamp"],
                reading["temperature"],
                reading["humidity"],
                reading["gas_raw"],
            ))

            return cursor.lastrowid


def get_readings(limit=100, db_path=None):
    """Return the newest sensor readings first."""
    if not isinstance(limit, int) or isinstance(limit, bool) or limit < 1:
        raise ValueError("limit must be a positive integer")

    database_url = _get_database_url(db_path)

    if database_url:
        with psycopg.connect(
            database_url,
            row_factory=dict_row,
        ) as connection:
            rows = connection.execute("""
                SELECT *
                FROM public.sensor_readings
                ORDER BY id DESC
                LIMIT %s
            """, (limit,)).fetchall()

            return [dict(row) for row in rows]

    path = Path(db_path) if db_path is not None else DB_PATH
    init_db(path)

    with closing(sqlite3.connect(path)) as connection:
        connection.row_factory = sqlite3.Row

        rows = connection.execute("""
            SELECT *
            FROM sensor_readings
            ORDER BY id DESC
            LIMIT ?
        """, (limit,)).fetchall()

        return [dict(row) for row in rows]